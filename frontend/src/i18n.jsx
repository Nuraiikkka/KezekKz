const Context = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem('lang') || 'ru'
    } catch {
      return 'ru'
    }
  })

  function setLang(value) {
    setLangState(value)
    try {
      localStorage.setItem('lang', value)
    } catch {
      return
    }
  }

  function t(key, fallback) {
    if (lang === 'en') return english[key] || fallback || key
    return words[lang][key] || english[key] || fallback || key
  }

  function reasonText(reason) {
    const prefix = 'Red flag symptom: '
    if (reason.startsWith(prefix)) {
      const flag = reason.slice(prefix.length).replaceAll(' ', '_')
      return `${t('reason.red')}: ${t('flag.' + flag, flag)}`
    }
    return t('reason.' + reason, reason)
  }

  const locale = lang === 'en' ? 'en-GB' : 'ru-RU'

  return <Context.Provider value={{ lang, locale, setLang, t, reasonText }}>{children}</Context.Provider>
}

export function useLang() {
  return useContext(Context)
}
